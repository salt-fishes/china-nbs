export function cleanQuery(query: string): string {
  let cleaned = stripRegion(query, regionNames());
  cleaned = cleaned
    .replace(/\d{4}\s*Q[1-4]/gi, ' ')
    .replace(/\d{4}\s*[-/]\s*\d{1,2}/g, ' ')
    .replace(/\d{1,2}\s*[-–—至]\s*\d{1,2}\s*月/g, ' ')
    .replace(/\d{4}\s*年?/g, ' ')
    .replace(/\d{1,2}\s*月/g, ' ')
    .replace(/\d{1,2}\s*日/g, ' ')
    .replace(/第?[一二三四1234]\s*季度/g, ' ')
    .replace(/(上半年|下半年|全年|年度)/g, ' ')
    .replace(/(中国|全国|最新|今年|去年|数据|统计|是多少|多少|查询|一下)/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return normalize(cleaned);
}

export function findCurated(
  query: string,
  period: Period,
  regionScope: 'national' | 'province' | 'city',
): CuratedEntry | undefined {
  const normalized = cleanQuery(query);
  if (!normalized) return undefined;

  let best: { entry: CuratedEntry; score: number } | undefined;

  for (const entry of CURATED) {
    if (entry.frequency !== period) continue;
    if (entry.regionScope !== 'any' && entry.regionScope !== regionScope) continue;

    for (const alias of entry.aliases) {
      const candidate = normalize(alias);
      if (!candidate || normalized !== candidate) continue;
      const score = 100 + candidate.length;
      if (!best || score > best.score) best = { entry, score };
    }
  }

  return best?.entry;
}
